#!/usr/bin/env python3
"""Generate src/core/eh_tables.c: const lookup tables for the renderer core.

Run from the repository root:  python3 tools/gen_tables.py
The output is committed; tests in tests/test_tables.c check every table
against its definition, so regenerate rather than hand-edit.
"""

import math
import pathlib

W = H = 360
LED_COUNT = 9
PALETTE_COUNT = 4

# Cosine palettes a + b*cos(2*pi*(c*t + d)); integer c keeps them cyclic so
# plasma indices can wrap without a seam.
PALETTES = [
    # event horizon: violet / magenta / amber
    ((0.50, 0.30, 0.55), (0.50, 0.30, 0.45), (1, 1, 1), (0.00, 0.10, 0.35)),
    # ice: cyan / blue / white
    ((0.35, 0.60, 0.75), (0.35, 0.40, 0.25), (1, 1, 1), (0.55, 0.50, 0.45)),
    # spectrum
    ((0.50, 0.50, 0.50), (0.50, 0.50, 0.50), (1, 1, 1), (0.00, 0.33, 0.67)),
    # ember: red / orange / green flashes
    ((0.55, 0.35, 0.20), (0.45, 0.35, 0.20), (1, 2, 1), (0.00, 0.15, 0.60)),
]


def rgb565(r, g, b):
    r, g, b = (max(0, min(255, int(math.floor(v + 0.5)))) for v in (r, g, b))
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def sin8():
    return [int(math.floor(127.5 + 127.5 * math.sin(2 * math.pi * i / 256) + 0.5)) for i in range(256)]


def inside(x, y):
    """Presentation mask: the 360x360 panel pixel's centre is within radius
    180. The framebuffer is native resolution, so pixels map 1:1 and the
    spans are exactly the mask (v1's 2x2 cell rule is no longer needed)."""
    dx, dy = 2 * x + 1 - W, 2 * y + 1 - H
    return dx * dx + dy * dy <= W * W


def spans():
    x0, x1 = [], []
    for y in range(H):
        xs = [x for x in range(W) if inside(x, y)]
        x0.append(xs[0] if xs else 0)
        x1.append(xs[-1] + 1 if xs else 0)
    return x0, x1


def palettes():
    out = []
    for a, b, c, d in PALETTES:
        pal = []
        for i in range(256):
            t = i / 256
            ch = [255 * (a[k] + b[k] * math.cos(2 * math.pi * (c[k] * t + d[k]))) for k in range(3)]
            pal.append(rgb565(*ch))
        out.append(pal)
    return out


def led_samples():
    out = []
    for k in range(LED_COUNT):
        theta = -math.pi / 2 + 2 * math.pi * k / LED_COUNT
        idx = []
        for r in (148.0, 160.0, 172.0):
            for dt in (-0.1, 0.0, 0.1):
                x = int(math.floor(W / 2 + r * math.cos(theta + dt)))
                y = int(math.floor(H / 2 + r * math.sin(theta + dt)))
                assert inside(x, y)
                idx.append(y * W + x)
        out.append(idx)
    return out


def c_array(values, per_line, fmt, indent="    "):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append(indent + ", ".join(fmt.format(v) for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    x0, x1 = spans()
    parts = [
        "/* Generated by tools/gen_tables.py; do not edit. */",
        '#include "eh/eh_tables.h"',
        "",
        "const uint8_t eh_sin8[256] = {",
        c_array(sin8(), 16, "{:3d}"),
        "};",
        "",
        "const uint16_t eh_span_x0[EH_FB_H] = {",
        c_array(x0, 18, "{:3d}"),
        "};",
        "",
        "const uint16_t eh_span_x1[EH_FB_H] = {",
        c_array(x1, 18, "{:3d}"),
        "};",
        "",
        "const eh_rgb565 eh_palettes[EH_PALETTE_COUNT][256] = {",
    ]
    for pal in palettes():
        parts += ["    {", c_array(pal, 12, "0x{:04X}", indent="        "), "    },"]
    parts += ["};", "", "const uint32_t eh_led_samples[EH_LED_COUNT][EH_LED_SAMPLES] = {"]
    for idx in led_samples():
        parts.append("    {" + ", ".join(f"{v:6d}" for v in idx) + "},")
    parts += ["};", ""]
    (root / "src" / "core" / "eh_tables.c").write_text("\n".join(parts))


if __name__ == "__main__":
    main()
