#!/usr/bin/env python3
"""Generate the dual-boot menu's torus tile from a host render.

    eh_cli frames --out DIR --at 7000
    python3 -I tools/gen_menu_art.py DIR/frame_07000.ppm device/menu/eh_menu_art.h

The menu shows our own torus beside the Wayfarer emblem (which it draws
procedurally). The frame is the host renderer's output, so the tile is ours
and may be committed; it contains nothing from stock.

A full RGB565 tile would cost 39 KB of the menu's 64 KiB slot, so the tile is
stored as 8-bit indices into a 256-colour RGB565 palette (median cut). The
output is deterministic: the ctest menu_art_current regenerates it and
compares.
"""
import sys

TILE = 140          # tile edge in pixels
CROP = 340          # source square: nearly the whole 360 px disc, so the knot fits
COLOURS = 256


def read_ppm(path):
    with open(path, "rb") as f:
        data = f.read()
    fields, pos = [], 0
    while len(fields) < 4:
        while data[pos:pos + 1].isspace():
            pos += 1
        if data[pos:pos + 1] == b"#":
            pos = data.index(b"\n", pos) + 1
            continue
        end = pos
        while not data[end:end + 1].isspace():
            end += 1
        fields.append(data[pos:end])
        pos = end
    if fields[0] != b"P6" or int(fields[3]) != 255:
        raise ValueError(f"{path}: not an 8-bit P6 PPM")
    w, h = int(fields[1]), int(fields[2])
    pixels = data[pos + 1:pos + 1 + 3 * w * h]
    if len(pixels) != 3 * w * h:
        raise ValueError(f"{path}: truncated")
    return w, h, pixels


def centre_tile(w, h, pixels):
    """Crop CROP x CROP around the frame centre and area-average it to TILE."""
    if w < CROP or h < CROP:
        raise ValueError(f"frame {w}x{h} smaller than the {CROP} px crop")
    x0, y0 = (w - CROP) // 2, (h - CROP) // 2
    edges = [i * CROP // TILE for i in range(TILE + 1)]
    out = []
    for ty in range(TILE):
        for tx in range(TILE):
            acc, n = [0, 0, 0], 0
            for sy in range(edges[ty], edges[ty + 1]):
                for sx in range(edges[tx], edges[tx + 1]):
                    i = 3 * ((y0 + sy) * w + x0 + sx)
                    for c in range(3):
                        acc[c] += pixels[i + c]
                    n += 1
            out.append(tuple((v + n // 2) // n for v in acc))
    return out


def median_cut(colours, n):
    """Median cut to at most n boxes. Returns (palette, index per pixel): each
    pixel maps to the mean of its own box. Ties break on pixel order, so the
    result is deterministic."""
    def spans(box):
        return [max(colours[i][c] for i in box) - min(colours[i][c] for i in box) for c in range(3)]

    boxes = [list(range(len(colours)))]
    while len(boxes) < n:
        best, best_key = None, None
        for b, box in enumerate(boxes):
            widest = max(spans(box))
            if widest == 0:
                continue
            key = (widest * len(box), -b)
            if best_key is None or key > best_key:
                best, best_key = b, key
        if best is None:
            break
        box = boxes.pop(best)
        s = spans(box)
        axis = s.index(max(s))
        box.sort(key=lambda i: (colours[i][axis], i))
        mid = len(box) // 2
        # Keep equal values on one side; the box spans >0, so a split exists.
        while 0 < mid < len(box) and colours[box[mid]][axis] == colours[box[mid - 1]][axis]:
            mid += 1
        if mid == len(box):
            mid = len(box) // 2
            while colours[box[mid]][axis] == colours[box[mid - 1]][axis]:
                mid -= 1
        boxes[best:best] = [box[:mid], box[mid:]]
    palette, index = [], [0] * len(colours)
    for b, box in enumerate(boxes):
        palette.append(tuple((sum(colours[i][c] for i in box) + len(box) // 2) // len(box) for c in range(3)))
        for i in box:
            index[i] = b
    return palette, index


def rgb565(c):
    r, g, b = c
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def header(palette, indices, source):
    pal = [rgb565(c) for c in palette] + [0] * (COLOURS - len(palette))
    lines = [
        f"/* GENERATED by tools/gen_menu_art.py from {source}: do not edit.",
        " * Our host render of the torus scene; nothing here comes from stock. */",
        "#ifndef EH_MENU_ART_H",
        "#define EH_MENU_ART_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define EH_MENU_TILE {TILE}",
        "",
        f"static const uint16_t eh_menu_torus_palette[{COLOURS}] = {{",
    ]
    for i in range(0, COLOURS, 12):
        lines.append("    " + " ".join(f"0x{v:04x}," for v in pal[i:i + 12]))
    lines += ["};", "", f"static const uint8_t eh_menu_torus_px[{TILE} * {TILE}] = {{"]
    for i in range(0, len(indices), 20):
        lines.append("    " + " ".join(f"{v}," for v in indices[i:i + 20]))
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main(argv):
    if len(argv) != 3:
        sys.exit("usage: gen_menu_art.py FRAME.ppm OUT.h")
    w, h, pixels = read_ppm(argv[1])
    tile = centre_tile(w, h, pixels)
    palette, indices = median_cut(tile, COLOURS)
    source = argv[1].rsplit("/", 1)[-1]
    with open(argv[2], "w") as f:
        f.write(header(palette, indices, source))


if __name__ == "__main__":
    main(sys.argv)
